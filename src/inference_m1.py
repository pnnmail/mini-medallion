"""N1.1 + N1.2 -- incremental testing, its null harness, and Romano-Wolf stepdown.

Two upgrades over M0, both aimed at the same failure mode:

1.1  The baseline is no longer zero, it is a model.  Every candidate is tested
     as `y ~ HAR(own history) + beta*X`, H0: beta = 0.  Out-of-sample testing
     protects against overfitting but NOT against confounding, and those are
     different failures -- a relationship confounded through volatility
     clustering is REQUIRED to reproduce out of sample.  In M0 the surviving
     candidate's t-stat was HIGHER on TEST than on TRAIN; that is the signature
     of a confound, not of a live effect.

1.2  Romano-Wolf stepdown replaces the plain max|t| threshold.  Both are
     bootstrap-calibrated FWER procedures, but stepdown regains power after each
     rejection instead of holding every test to the single hardest threshold.

The null is generated by a RESTRICTED residual bootstrap: fit the baseline, then
resample its residuals in stationary blocks and rebuild the target under
beta = 0, holding X fixed.  This preserves the baseline dynamics, the candidate's
own structure, and the dependence ACROSS candidates -- only the candidate-to-
residual link is destroyed, which is exactly the hypothesis under test.
"""
from __future__ import annotations

import numpy as np
from scipy import stats as sps

from stats_engine import stationary_bootstrap_index


# ------------------------------------------------------------------ OLS + HAC
def _prep(X: np.ndarray):
    XtX = X.T @ X
    XtX_inv = np.linalg.inv(XtX)
    return XtX_inv, XtX_inv @ X.T


def nw_tstat_last(y: np.ndarray, X: np.ndarray, lag: int, XtX_inv=None, P=None):
    """OLS of y on X (intercept must already be a column); NW t on the LAST column."""
    n, k = X.shape
    if XtX_inv is None:
        XtX_inv, P = _prep(X)
    beta = P @ y
    e = y - X @ beta
    u = X * e[:, None]
    S = u.T @ u
    L = max(int(lag), 0)
    for l in range(1, L + 1):
        w = 1.0 - l / (L + 1.0)
        G = u[l:].T @ u[:-l]
        S = S + w * (G + G.T)
    V = XtX_inv @ S @ XtX_inv
    v = V[-1, -1]
    if not np.isfinite(v) or v <= 0:
        return float(beta[-1]), np.nan, np.nan
    t = float(beta[-1] / np.sqrt(v))
    return float(beta[-1]), t, float(2.0 * (1.0 - sps.norm.cdf(abs(t))))


def restricted_fit(y: np.ndarray, Xb: np.ndarray):
    """Fit the baseline-only model; return fitted values and residuals."""
    XtX_inv, P = _prep(Xb)
    beta = P @ y
    fitted = Xb @ beta
    return fitted, y - fitted, beta


# ------------------------------------------------------ null + Romano-Wolf
def incremental_null_bootstrap(y, Xb, cand_matrix, lag, n_rep, mean_block, rng):
    """Bootstrap the joint distribution of incremental |t| under H0: beta = 0.

    `cand_matrix` is (n, K): one column per candidate, tested one at a time.
    Returns (T_obs (K,), T_star (n_rep, K)).

    All K candidates see the SAME resampled target within a replication, so the
    dependence among the tests -- which is what a max-statistic threshold and a
    stepdown procedure both need -- is preserved rather than assumed away.
    """
    y = np.asarray(y, float)
    Xb = np.asarray(Xb, float)
    C = np.asarray(cand_matrix, float)
    n, K = C.shape

    fitted, resid, _ = restricted_fit(y, Xb)

    prep = []
    T_obs = np.full(K, np.nan)
    B_obs = np.full(K, np.nan)
    P_obs = np.full(K, np.nan)
    for j in range(K):
        Xf = np.column_stack([Xb, C[:, j]])
        try:
            XtX_inv, P = _prep(Xf)
        except np.linalg.LinAlgError:
            prep.append(None)
            continue
        prep.append((Xf, XtX_inv, P))
        b, t, p = nw_tstat_last(y, Xf, lag, XtX_inv, P)
        B_obs[j], T_obs[j], P_obs[j] = b, t, p

    T_star = np.full((n_rep, K), np.nan)
    for r in range(n_rep):
        idx = stationary_bootstrap_index(n, mean_block, rng)
        y_star = fitted + resid[idx]
        for j in range(K):
            if prep[j] is None:
                continue
            Xf, XtX_inv, P = prep[j]
            _, t, _ = nw_tstat_last(y_star, Xf, lag, XtX_inv, P)
            T_star[r, j] = t
    return B_obs, T_obs, P_obs, T_star


def romano_wolf(t_obs: np.ndarray, t_star: np.ndarray, alpha: float = 0.05):
    """Romano-Wolf stepdown on |t|. Returns (rejected, adjusted_p, step_thresholds).

    Step 1 compares the largest |t| against the bootstrap distribution of the
    maximum over ALL hypotheses. After each rejection the rejected hypothesis is
    dropped and the maximum is recomputed over what remains, so later tests are
    not held to the hardest threshold in the family.
    """
    a_obs = np.abs(np.asarray(t_obs, float))
    a_star = np.abs(np.asarray(t_star, float))
    K = len(a_obs)
    rejected = np.zeros(K, bool)
    adj_p = np.ones(K)
    thresholds = np.full(K, np.nan)

    order = np.argsort(-np.where(np.isfinite(a_obs), a_obs, -np.inf))
    remaining = list(order)
    prev_p = 0.0
    while remaining:
        sub = a_star[:, remaining]
        with np.errstate(invalid="ignore"):
            maxstat = np.nanmax(sub, axis=1)
        maxstat = maxstat[np.isfinite(maxstat)]
        if len(maxstat) < 50:
            break
        j = remaining[0]
        if not np.isfinite(a_obs[j]):
            remaining.pop(0)
            continue
        thr = float(np.quantile(maxstat, 1.0 - alpha))
        thresholds[j] = thr
        p = float((maxstat >= a_obs[j]).mean())
        p = max(p, prev_p)                    # monotone, as the procedure requires
        prev_p = p
        adj_p[j] = p
        if a_obs[j] > thr:
            rejected[j] = True
            remaining.pop(0)
        else:
            for jj in remaining:
                adj_p[jj] = max(adj_p[jj], p)
                thresholds[jj] = thr
            break
    return rejected, adj_p, thresholds


def group_candidates_by_sample(y, Xb_df, cand_df, split_mask, family_map):
    """Split candidates into two blocks that share a usable sample.

    Without this, one short candidate (the GLD ETF starts in 2004) would force
    the whole family onto its sample and silently discard the extended SPY
    history that config declared before any result was seen.

    The split is STRUCTURAL, not a tuned threshold: cross-asset volatility
    candidates require other instruments to already exist, everything else needs
    only the target, VIX, the macro series or the calendar. FWER is then
    controlled within each block, and a conservative pooled threshold is
    reported across blocks.
    """
    import pandas as pd
    base = pd.concat([y.rename("__y__"), Xb_df], axis=1)
    base_ok = base.notna().all(axis=1).to_numpy() & np.asarray(split_mask)
    blocks = {"own_and_market": [], "cross_asset": []}
    for c in cand_df.columns:
        key = "cross_asset" if family_map.get(c) == "cross_asset_vol" else "own_and_market"
        blocks[key].append(c)
    out = []
    for name, cols in blocks.items():
        if not cols:
            continue
        ok = base_ok.copy()
        for c in cols:
            ok = ok & cand_df[c].notna().to_numpy()
        if ok.sum() >= 300:
            out.append((name, ok, cols))
    return out
